// Submit to LLM
document.getElementById('submit-btn').addEventListener('click', async () => {
  const prompt = document.getElementById('prompt-input').value;
  document.getElementById('prompt-input').value = ""; // Clear input field
  const messagesDiv = document.getElementById('response-display');

  // Check if a model is selected
  if (!selectedModel) {
    const errorContainer = document.createElement('div');
    errorContainer.innerHTML = `
            <strong style="color: #990000ff;">System:</strong><br>
            <span>Error: Please select LLM Model</span>
        `;
    messagesDiv.appendChild(errorContainer);
    messagesDiv.scrollTop = messagesDiv.scrollHeight;
    return;
  }
  if (!prompt) {
    const errorContainer = document.createElement('div');
    errorContainer.innerHTML = `
            <strong style="color: #990000ff;">System:</strong><br>
            <span>Error: Provide prompt</span>
        `;
    messagesDiv.appendChild(errorContainer);
    messagesDiv.scrollTop = messagesDiv.scrollHeight;
    return;
  }


  // Initialize conversation history if it's not already defined
  if (!window.conversationHistory) {
    window.conversationHistory = [];
  }

  // Add user's message to history FIRST
  conversationHistory.push({
    role: "user",
    content: prompt
  });


  displayMessage(prompt, "user")

  messagesDiv.scrollTop = messagesDiv.scrollHeight; // Scroll to bottom

  try {
    // Get streaming response from LLM
    console.log(prompt)
    const response = await askQuestion(prompt, selectedModel);

    // Create streaming message container
    const streamingContentDiv = displayMessage('', 'assistant', true);

    let LLMcontent = "";

    // Stream the response from LLM
    for await (const part of response) {
      console.log(part)
      LLMcontent += part.type == "text" ? part.text : "";
      streamingContentDiv.textContent = LLMcontent;
      messagesDiv.scrollTop = messagesDiv.scrollHeight; // Auto scroll to the bottom
    }
    updateStreamingMessage(streamingContentDiv, LLMcontent);
    console.log(LLMcontent);

    // Add LLM's response to history after streaming
    conversationHistory.push({
      role: "assistant",
      content: LLMcontent
    });

  } catch (error) {
    console.log(error)
    displayMessage(`>Error: ${typeof error.error == "string" ? error.error : error.error.message}`);
    console.error('Error getting LLM response:', error);
  }
});

// Toggle config panel functionality
const configToggleBtn = document.getElementById('config-toggle-btn');
const configPanel = document.querySelector('.config-panel');
let isPanelCollapsed = false;

configToggleBtn.addEventListener('click', () => {
  isPanelCollapsed = !isPanelCollapsed;

  if (isPanelCollapsed) {
    configPanel.classList.add('collapsed');
    configToggleBtn.classList.add('panel-collapsed');
    // Update tooltip positions when collapsed
    updateTooltipPositions();
  } else {
    configPanel.classList.remove('collapsed');
    configToggleBtn.classList.remove('panel-collapsed');
  }
});

// Function to update tooltip positions dynamically
function updateTooltipPositions() {
  const formGroups = document.querySelectorAll('.config-panel.collapsed .form-group');
  formGroups.forEach(group => {
    const rect = group.getBoundingClientRect();
    const tooltipTop = rect.top + rect.height / 2;
    group.style.setProperty('--tooltip-top', tooltipTop + 'px');
  });
}

// Update tooltip positions on scroll or resize
window.addEventListener('scroll', () => {
  if (isPanelCollapsed) {
    updateTooltipPositions();
  }
});

window.addEventListener('resize', () => {
  if (isPanelCollapsed) {
    updateTooltipPositions();
  }
});



